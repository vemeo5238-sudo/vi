/* ---------- Bộ máy áp dụng bản dịch ---------- */
(function () {
  let on = false;
  try { on = localStorage.getItem("va_lang") === "vi"; } catch (e) {}
  if (!on) return;
  document.documentElement.lang = "vi";
  document.documentElement.classList.add("lang-vi");
  const norm = s => s.replace(/\s+/g, " ").trim();
  const tr = s => {
    const k = norm(s);
    if (!k) return null;
    if (Object.prototype.hasOwnProperty.call(VI_DICT, k)) return VI_DICT[k];
    for (const [re, f] of VI_RULES) { const m = k.match(re); if (m) return f(...m); }
    return null;
  };
  const SKIP = "script,style,svg,option,.notranslate,[translate=no]";
  const doText = n => {
    const p = n.parentElement;
    if (!p || p.closest(SKIP)) return;
    const v = n.nodeValue, t = tr(v);
    if (t != null && t !== norm(v)) n.nodeValue = v.match(/^\s*/)[0] + t + v.match(/\s*$/)[0];
  };
  const ATTRS = ["placeholder", "aria-label", "title", "alt", "label"];
  const doEl = el => {
    if (el.closest && el.closest(".notranslate")) return;
    ATTRS.forEach(a => { const v = el.getAttribute && el.getAttribute(a); if (v) { const t = tr(v); if (t != null) el.setAttribute(a, t); } });
  };
  const walk = root => {
    if (root.nodeType === 3) return doText(root);
    if (root.nodeType !== 1) return;
    doEl(root);
    root.querySelectorAll("*").forEach(doEl);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let n; while ((n = w.nextNode())) doText(n);
  };
  const run = () => {
    walk(document.body);
    const t = tr(document.title); if (t) document.title = t;
    new MutationObserver(ms => ms.forEach(m => {
      if (m.type === "characterData") doText(m.target);
      else m.addedNodes.forEach(walk);
    })).observe(document.body, { childList: true, subtree: true, characterData: true });
  };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", run); else run();
})();
